#!/usr/bin/env node
// Stage the ad's media from ../assets/video-src/ into media/.
//
// For every slot in slots.json:
//   - a real file in ../assets/video-src/ is normalised with ffmpeg
//     (photos -> JPEG <= 2400 px wide; films -> H.264 yuv420p, no audio,
//     short side <= 1080) and written to media/<slot>.jpg|mp4;
//   - an optional "<name>-16x9.<ext>" sibling feeds the 16:9 render
//     (media/<slot>-16x9.*); otherwise the 16:9 render centre-crops the same file;
//   - a missing file falls back to the marked plate in media/placeholders/.
// It also writes media/manifest.js, which tells the composition which slots are
// placeholders and which carry the "AI-generated sample" label.
//
// Usage: node scripts/sync-media.mjs        (run from video/, needs ffmpeg)

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, parse, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "..", "assets", "video-src");
const OUT = join(ROOT, "media");
const PLACEHOLDERS = join(OUT, "placeholders");
const STAMP = join(OUT, ".stamp.json");

const PHOTO_EXT = [".jpg", ".jpeg", ".png", ".webp", ".heic"];
const FILM_EXT = [".mp4", ".mov", ".m4v", ".webm"];
const MIN_SECONDS = { v1: 4.5, v2: 2.0, v3: 2.0, v4: 2.0, v5: 9.5 };

const { slots } = JSON.parse(readFileSync(join(ROOT, "slots.json"), "utf8"));
const stamp = existsSync(STAMP) ? JSON.parse(readFileSync(STAMP, "utf8")) : {};
mkdirSync(OUT, { recursive: true });

const available = existsSync(SRC) ? readdirSync(SRC) : [];

function findSource(fileName, suffix = "") {
  const { name } = parse(fileName);
  const want = (name + suffix).toLowerCase();
  const exts = PHOTO_EXT.includes(extname(fileName).toLowerCase()) ? PHOTO_EXT : FILM_EXT;
  const hit = available.find((f) => {
    const p = parse(f);
    return p.name.toLowerCase() === want && exts.includes(p.ext.toLowerCase());
  });
  return hit ? join(SRC, hit) : null;
}

function ffmpeg(args) {
  execFileSync("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", ...args], { stdio: "inherit" });
}

function duration(file) {
  try {
    return parseFloat(
      execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString(),
    );
  } catch {
    return NaN;
  }
}

function stage(slot, src, dest) {
  const key = relative(ROOT, dest);
  // film plates (and the full-bleed p2 plate) exist per format; the 3:2 p1 plate serves both
  const perFormat = join(PLACEHOLDERS, parse(dest).base);
  const plate = existsSync(perFormat) ? perFormat : join(PLACEHOLDERS, `${slot.id}.jpg`);
  const from = src ?? plate;
  const sig = `${from}:${statSync(from).size}:${statSync(from).mtimeMs}`;
  if (stamp[key] === sig && existsSync(dest)) return;
  if (!src) {
    copyFileSync(plate, dest);
  } else if (slot.kind === "photo") {
    ffmpeg(["-i", src, "-vf", "scale='min(2400,iw)':-2", "-frames:v", "1", "-q:v", "2", dest]);
  } else {
    ffmpeg([
      "-i", src, "-an",
      "-vf", "scale='if(gt(iw,ih),-2,min(1080,iw))':'if(gt(iw,ih),min(1080,ih),-2)'",
      // 30 fps with a keyframe every second: HyperFrames seeks each frame, sparse keyframes freeze
      "-r", "30", "-c:v", "libx264", "-preset", "medium", "-crf", "18", "-g", "30", "-keyint_min", "30", "-pix_fmt", "yuv420p",
      "-movflags", "+faststart", dest,
    ]);
  }
  stamp[key] = sig;
}

const manifest = {};
const rows = [];
for (const slot of slots) {
  const ext = slot.kind === "photo" ? ".jpg" : ".mp4";
  const main = findSource(slot.file);
  const wide = findSource(slot.file, "-16x9") ?? main;
  stage(slot, main, join(OUT, slot.id + ext));
  stage(slot, wide, join(OUT, `${slot.id}-16x9${ext}`));
  manifest[slot.id] = { placeholder: !main, ai: Boolean(main && slot.ai) };
  let note = main ? relative(join(ROOT, ".."), main) : "PLACEHOLDER";
  if (main && slot.kind === "film") {
    const d = duration(main);
    if (d < MIN_SECONDS[slot.id]) note += `  (only ${d.toFixed(1)} s, needs ${MIN_SECONDS[slot.id]} s: last frame will hold)`;
  }
  if (main && slot.ai) note += "  [AI-generated sample label ON]";
  rows.push(`  ${slot.id.padEnd(3)} ${slot.file.padEnd(24)} ${note}`);
}

writeFileSync(
  join(OUT, "manifest.js"),
  "// Generated by scripts/sync-media.mjs — do not edit.\n" +
    `window.AOW_MEDIA = ${JSON.stringify(manifest, null, 2)};\n`,
);
writeFileSync(STAMP, JSON.stringify(stamp, null, 2));
console.log(`media staged from ${relative(ROOT, SRC)}:\n${rows.join("\n")}`);
